-- NHL Fantasy Pool foundation schema
-- Timezone for league cutoffs: America/Moncton.
-- This migration establishes secure data structures; it does not import NHL data
-- or activate scheduled processing. Configure Supabase Auth and Edge Functions separately.

create extension if not exists pgcrypto;

create type public.league_role as enum ('manager', 'commissioner');
create type public.roster_status as enum ('active', 'reserve');
create type public.transaction_kind as enum ('add_drop', 'reserve_activate', 'trade');
create type public.transaction_status as enum ('pending', 'processed', 'rejected', 'cancelled');
create type public.player_position as enum ('F', 'D', 'G');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role public.league_role not null default 'manager',
  created_at timestamptz not null default now()
);

create table public.fantasy_teams (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  conference text not null check (conference in ('Eastern', 'Western')),
  division text not null,
  nhl_identity text not null,
  manager_id uuid unique references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.nhl_players (
  id bigint generated by default as identity primary key,
  nhl_player_id bigint unique,
  full_name text not null,
  nhl_team_abbrev text,
  position public.player_position not null,
  salary numeric(12,2) not null default 0 check (salary >= 0),
  active boolean not null default true,
  source_updated_at timestamptz,
  created_at timestamptz not null default now()
);

-- A player may be selected by multiple fantasy teams. Uniqueness is only within a team.
create table public.roster_entries (
  id uuid primary key default gen_random_uuid(),
  fantasy_team_id uuid not null references public.fantasy_teams(id) on delete cascade,
  player_id bigint not null references public.nhl_players(id),
  status public.roster_status not null default 'active',
  roster_position public.player_position not null,
  added_at timestamptz not null default now(),
  unique (fantasy_team_id, player_id)
);

create table public.league_transactions (
  id uuid primary key default gen_random_uuid(),
  fantasy_team_id uuid not null references public.fantasy_teams(id) on delete cascade,
  submitted_by uuid not null references public.profiles(id),
  kind public.transaction_kind not null,
  add_player_id bigint references public.nhl_players(id),
  drop_player_id bigint references public.nhl_players(id),
  target_status public.roster_status,
  status public.transaction_status not null default 'pending',
  submitted_at timestamptz not null default now(),
  effective_at timestamptz not null,
  processed_at timestamptz,
  decision_note text,
  check (add_player_id is not null or drop_player_id is not null or target_status is not null)
);

create table public.nhl_games (
  id bigint generated by default as identity primary key,
  nhl_game_id bigint unique,
  season text not null default '20262027',
  game_date date not null,
  start_time timestamptz,
  home_team_abbrev text not null,
  away_team_abbrev text not null,
  status text not null default 'scheduled' check (status in ('scheduled', 'live', 'final', 'postponed', 'cancelled')),
  home_score integer check (home_score is null or home_score >= 0),
  away_score integer check (away_score is null or away_score >= 0),
  source_updated_at timestamptz,
  updated_at timestamptz not null default now()
);

create table public.nhl_player_game_stats (
  id bigint generated by default as identity primary key,
  game_id bigint not null references public.nhl_games(id) on delete cascade,
  player_id bigint not null references public.nhl_players(id) on delete cascade,
  goals integer not null default 0 check (goals >= 0),
  assists integer not null default 0 check (assists >= 0),
  goalie_wins integer not null default 0 check (goalie_wins between 0 and 1),
  goalie_ot_losses integer not null default 0 check (goalie_ot_losses between 0 and 1),
  goalie_ties_after_60 integer not null default 0 check (goalie_ties_after_60 between 0 and 1),
  source_updated_at timestamptz,
  unique (game_id, player_id)
);

create table public.fantasy_matchups (
  id uuid primary key default gen_random_uuid(),
  season text not null default '20262027',
  week_number integer not null check (week_number between 1 and 40),
  fantasy_team_id uuid not null references public.fantasy_teams(id) on delete cascade,
  opponent_team_id uuid not null references public.fantasy_teams(id) on delete cascade,
  starts_at timestamptz not null,
  closes_at timestamptz not null,
  status text not null default 'open' check (status in ('open', 'final')),
  team_points numeric(10,2) not null default 0,
  opponent_points numeric(10,2) not null default 0,
  result text check (result is null or result in ('W', 'T', 'L')),
  finalized_at timestamptz,
  check (fantasy_team_id <> opponent_team_id),
  check (closes_at > starts_at),
  unique (season, week_number, fantasy_team_id)
);

create table public.fantasy_player_daily_points (
  id bigint generated by default as identity primary key,
  fantasy_team_id uuid not null references public.fantasy_teams(id) on delete cascade,
  player_id bigint not null references public.nhl_players(id),
  scoring_date date not null,
  points numeric(10,2) not null default 0,
  goals integer not null default 0,
  assists integer not null default 0,
  goalie_points numeric(10,2) not null default 0,
  calculated_at timestamptz not null default now(),
  unique (fantasy_team_id, player_id, scoring_date)
);

create table public.league_settings (
  id integer primary key default 1 check (id = 1),
  season text not null default '20262027',
  timezone text not null default 'America/Moncton',
  regular_season_moves_per_team integer not null default 5 check (regular_season_moves_per_team >= 0),
  active_forwards integer not null default 12 check (active_forwards = 12),
  active_defencemen integer not null default 6 check (active_defencemen = 6),
  active_goalies integer not null default 2 check (active_goalies = 2),
  max_reserve_players integer not null default 3 check (max_reserve_players = 3),
  salary_cap numeric(12,2) not null default 100000000 check (salary_cap > 0),
  updated_at timestamptz not null default now()
);

insert into public.league_settings (id) values (1) on conflict (id) do nothing;

create index roster_entries_team_status_idx on public.roster_entries (fantasy_team_id, status);
create index transactions_pending_effective_idx on public.league_transactions (status, effective_at);
create index nhl_games_date_idx on public.nhl_games (game_date, start_time);
create index player_daily_points_team_date_idx on public.fantasy_player_daily_points (fantasy_team_id, scoring_date);
create index matchups_week_idx on public.fantasy_matchups (season, week_number, fantasy_team_id);

create or replace function public.is_commissioner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'commissioner'
  );
$$;

create or replace function public.owns_team(target_team_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.fantasy_teams t
    where t.id = target_team_id and t.manager_id = (select auth.uid())
  );
$$;

-- Users may not promote themselves to commissioner by editing their profile.
create or replace function public.protect_profile_role()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.role is distinct from old.role
     and not public.is_commissioner() then
    raise exception 'Only a commissioner may change league roles';
  end if;
  return new;
end;
$$;

create trigger protect_profile_role_before_update
before update on public.profiles
for each row execute function public.protect_profile_role();

