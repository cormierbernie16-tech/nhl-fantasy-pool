-- Authenticated managers can see league information; only their team is editable.
create policy "profiles readable by authenticated users"
on public.profiles for select to authenticated using (true);
create policy "profile owner can insert self"
on public.profiles for insert to authenticated with check (id = (select auth.uid()));
create policy "profile owner can update own display name"
on public.profiles for update to authenticated
using (id = (select auth.uid()) or public.is_commissioner())
with check (id = (select auth.uid()) or public.is_commissioner());

create policy "teams readable by authenticated users"
on public.fantasy_teams for select to authenticated using (true);
create policy "commissioner manages teams"
on public.fantasy_teams for all to authenticated
using (public.is_commissioner()) with check (public.is_commissioner());

